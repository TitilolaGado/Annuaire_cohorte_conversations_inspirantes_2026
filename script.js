let currentView = "cards";

function normalize(value) {
  return String(value || "")
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "");
}

function initials(name) {
  return name
    .split(/\s+/)
    .filter(Boolean)
    .slice(0, 2)
    .map(part => part[0])
    .join("")
    .toUpperCase();
}

function getUnique(field) {
  return [...new Set(beneficiaries.map(item => item[field]).filter(Boolean))].sort((a, b) => a.localeCompare(b, "fr"));
}

function fillSelect(select, values) {
  values.forEach(value => {
    const option = document.createElement("option");
    option.value = value;
    option.textContent = value;
    select.appendChild(option);
  });
}

function renderStats() {
  elements.statTotal.textContent = beneficiaries.length;
  elements.statRegions.textContent = getUnique("region").length;
  elements.statFunctions.textContent = getUnique("function").length;
}

function renderRegionSummary() {
  elements.regionSummary.innerHTML = "";
  zoneSummary.forEach(zone => {
    const card = document.createElement("article");
    card.className = "region-card";
    card.tabIndex = 0;
    card.setAttribute("role", "button");
    card.setAttribute("aria-label", `Filtrer la région ${zone.zone}`);
    card.innerHTML = `
      <div class="region-top">
        <h3>${zone.zone}</h3>
        <span class="count-badge">${zone.count}</span>
      </div>
      <p><strong>Départements :</strong> ${zone.departments}</p>
      <p><strong>Communes :</strong> ${zone.communes}</p>
    `;
    const apply = () => {
      elements.regionFilter.value = zone.zone;
      renderDirectory();
      document.querySelector("#annuaire").scrollIntoView({ behavior: "smooth" });
    };
    card.addEventListener("click", apply);
    card.addEventListener("keydown", event => {
      if (event.key === "Enter" || event.key === " ") {
        event.preventDefault();
        apply();
      }
    });
    elements.regionSummary.appendChild(card);
  });
}

function renderFunctionSummary() {
  elements.functionSummary.innerHTML = "";
  functionSummary.forEach(item => {
    const pill = document.createElement("button");
    pill.type = "button";
    pill.className = "function-pill";
    pill.textContent = `${item.function} · ${item.count}`;
    pill.addEventListener("click", () => {
      elements.functionFilter.value = item.function;
      renderDirectory();
      document.querySelector("#annuaire").scrollIntoView({ behavior: "smooth" });
    });
    elements.functionSummary.appendChild(pill);
  });
}

function filterData() {
  const search = normalize(elements.searchInput.value);
  const region = elements.regionFilter.value;
  const fn = elements.functionFilter.value;

  return beneficiaries.filter(item => {
    const haystack = normalize(`${item.name} ${item.commune} ${item.region} ${item.department} ${item.function} ${item.profile} ${item.email}`);
    const matchesSearch = !search || haystack.includes(search);
    const matchesRegion = !region || item.region === region;
    const matchesFunction = !fn || item.function === fn;
    return matchesSearch && matchesRegion && matchesFunction;
  });
}

function renderCards(data) {
  elements.cardsView.innerHTML = "";
  if (!data.length) {
    elements.cardsView.innerHTML = `<article class="card"><h3>Aucun résultat</h3><p>Essayez d’élargir votre recherche ou de réinitialiser les filtres.</p></article>`;
    return;
  }

  data.forEach(item => {
    const card = document.createElement("article");
    card.className = "card";
    card.innerHTML = `
      <div class="card-head">
        <div class="avatar" aria-hidden="true">${initials(item.name)}</div>
        <div>
          <h3>${item.name}</h3>
          <p>${item.profile}</p>
        </div>
      </div>
      <div class="badges">
        <span class="badge">📍 ${item.region}</span>
        <span class="badge">${item.commune}</span>
        <span class="badge">${item.department}</span>
      </div>
      <p><strong>Domaine :</strong> ${item.function}</p>
      <div class="contact">
        <p><strong>Téléphone :</strong> ${item.phone || "À confirmer"}</p>
        <p><strong>Email :</strong> ${item.email ? `<a href="mailto:${item.email}">${item.email}</a>` : "À confirmer"}</p>
      </div>
    `;
    elements.cardsView.appendChild(card);
  });
}

function renderTable(data) {
  elements.tableBody.innerHTML = "";
  data.forEach(item => {
    const tr = document.createElement("tr");
    tr.innerHTML = `
      <td><strong>${item.name}</strong></td>
      <td>${item.region}<br><small>${item.department}</small></td>
      <td>${item.commune}</td>
      <td>${item.function}</td>
      <td>${item.profile}</td>
      <td>${item.phone || ""}<br>${item.email ? `<a href="mailto:${item.email}">${item.email}</a>` : ""}</td>
    `;
    elements.tableBody.appendChild(tr);
  });
}

function renderDirectory() {
  const data = filterData();
  elements.resultCount.textContent = data.length;
  renderCards(data);
  renderTable(data);
}

function changeView(view) {
  currentView = view;
  elements.switchButtons.forEach(button => {
    button.classList.toggle("active", button.dataset.view === view);
  });
  elements.cardsView.classList.toggle("hidden", view !== "cards");
  elements.tableView.classList.toggle("hidden", view !== "table");
}

function init() {
  fillSelect(elements.regionFilter, getUnique("region"));
  fillSelect(elements.functionFilter, getUnique("function"));
  renderStats();
  renderRegionSummary();
  renderFunctionSummary();
  renderDirectory();

  elements.searchInput.addEventListener("input", renderDirectory);
  elements.regionFilter.addEventListener("change", renderDirectory);
  elements.functionFilter.addEventListener("change", renderDirectory);

  elements.resetBtn.addEventListener("click", () => {
    elements.searchInput.value = "";
    elements.regionFilter.value = "";
    elements.functionFilter.value = "";
    renderDirectory();
  });

  elements.switchButtons.forEach(button => {
    button.addEventListener("click", () => changeView(button.dataset.view));
  });

  elements.printBtn.addEventListener("click", () => window.print());
}

document.addEventListener("DOMContentLoaded", init);
